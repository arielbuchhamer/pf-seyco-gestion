-- =====================================================================
-- MÓDULO 4 · SEGUIMIENTO DE OBRA
-- Gastos reales y certificaciones (cobros) de cada obra.  2 tablas.
-- Junto con el avance de las tareas alimentan el Portafolio y los
-- indicadores del proyecto.
-- =====================================================================
-- Requiere: 2-gestionDeProyectos.sql (apunta a proyecto).
-- Idempotente (IF NOT EXISTS): se puede correr más de una vez.
-- =====================================================================

BEGIN;

-- costo_real: gastos reales de la obra por rubro, para comparar con lo cotizado.
CREATE TABLE IF NOT EXISTS public.costo_real
(
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id bigint         NOT NULL REFERENCES public.proyecto (id),
    fecha       date           NOT NULL,
    rubro       varchar(20)    NOT NULL
        CHECK (rubro IN ('MANO_OBRA', 'EQUIPOS', 'MATERIALES', 'TERCEROS')),
    descripcion varchar(300)   NOT NULL,
    comprobante varchar(100),
    monto       numeric(19, 2) NOT NULL
);

-- certificacion: certificados de obra (= facturas al cliente por lo ejecutado).
CREATE TABLE IF NOT EXISTS public.certificacion
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id   bigint         NOT NULL REFERENCES public.proyecto (id),
    numero        integer        NOT NULL,
    tipo          varchar(20)    NOT NULL
        CHECK (tipo IN ('ANTICIPO', 'AVANCE', 'FINAL')),
    fecha_emision date           NOT NULL,
    porcentaje    numeric(7, 2),
    monto         numeric(19, 2) NOT NULL,
    nro_factura   varchar(50),
    estado        varchar(20)    NOT NULL
        CHECK (estado IN ('PENDIENTE_COBRO', 'COBRADA')),
    fecha_cobro   date,
    observaciones varchar(500)
);

COMMIT;
