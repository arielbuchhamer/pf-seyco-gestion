-- =====================================================================
-- MÓDULO 3 · PRESUPUESTO
-- Cotización de cada obra y sus renglones.  2 tablas.
-- =====================================================================
-- Requiere: 2-gestionDeProyectos.sql (apunta a proyecto y a tarea).
-- Idempotente (IF NOT EXISTS): se puede correr más de una vez.
-- =====================================================================

BEGIN;

-- presupuesto: cotización de la obra (1 a 1 con proyecto).
CREATE TABLE IF NOT EXISTS public.presupuesto
(
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id bigint      NOT NULL UNIQUE REFERENCES public.proyecto (id),
    estado      varchar(20) NOT NULL
        CHECK (estado IN ('ABIERTO', 'CERRADO')),
    fecha       date,
    plazo_dias  integer,
    total       numeric(19, 2)
);

-- item_presupuesto: renglones del presupuesto, en árbol (padre_id):
-- CAPITULO > GRUPO > ARMADO > ITEM. Puede vincularse a una tarea.
-- Montos por rubro: mano de obra, equipos, materiales y terceros.
CREATE TABLE IF NOT EXISTS public.item_presupuesto
(
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id bigint      NOT NULL REFERENCES public.presupuesto (id),
    padre_id       bigint      REFERENCES public.item_presupuesto (id),
    tarea_id       bigint      REFERENCES public.tarea (id),
    tipo           varchar(20) NOT NULL
        CHECK (tipo IN ('CAPITULO', 'GRUPO', 'ARMADO', 'ITEM')),
    numero         varchar(20),
    orden          integer,
    codigo         varchar(100),
    descripcion    varchar(1000),
    unidad         varchar(20),
    cantidad       numeric(19, 4),
    mano_obra      numeric(19, 2),
    equipos        numeric(19, 2),
    materiales     numeric(19, 2),
    terceros       numeric(19, 2),
    total          numeric(19, 2)
);

COMMIT;
