-- =====================================================================
-- MÓDULO 1 · GESTIÓN DE ACCESOS
-- Usuarios, roles, permisos (módulos y paneles), sesiones y recuperación
-- de contraseña.  9 tablas.
-- =====================================================================
-- Orden de ejecución: 1 → 2 → 3 → 4 (ver README.md de esta carpeta).
-- Este módulo no depende de ningún otro.
-- Idempotente (IF NOT EXISTS): se puede correr más de una vez.
-- Los datos iniciales (módulos, paneles, roles admin/visor y usuarios de
-- prueba) los carga el backend al arrancar (config/DataSeeder.java).
-- =====================================================================

BEGIN;

-- usuarios: baja lógica (fecha_baja). El email sólo no puede repetirse
-- entre usuarios activos (lo valida el backend).
CREATE TABLE IF NOT EXISTS public.usuarios
(
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               varchar(50)  NOT NULL,
    nombre              varchar(50),
    apellido            varchar(50),
    contrasena          varchar(255) NOT NULL,          -- hash BCrypt
    dni                 integer,
    telefono            varchar(255),
    fecha_alta          timestamptz  NOT NULL,
    fecha_actualizacion timestamptz,
    fecha_baja          timestamptz
);

-- roles: token_duracion = minutos que dura una sesión (con varios roles, el mayor).
CREATE TABLE IF NOT EXISTS public.roles
(
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         varchar(50) NOT NULL UNIQUE,
    token_duracion integer     NOT NULL DEFAULT 60
);

-- modulos: recursos sobre los que se dan permisos (proyectos, tareas, usuarios, roles).
CREATE TABLE IF NOT EXISTS public.modulos
(
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(50) NOT NULL UNIQUE
);

-- paneles: pantallas del frontend que un rol puede ver.
CREATE TABLE IF NOT EXISTS public.paneles
(
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(50) NOT NULL UNIQUE
);

-- roles_usuarios: qué roles tiene cada usuario (N a N).
CREATE TABLE IF NOT EXISTS public.roles_usuarios
(
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol     bigint NOT NULL REFERENCES public.roles (id)    ON DELETE CASCADE,
    id_usuario bigint NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
    UNIQUE (id_rol, id_usuario)
);

-- roles_modulos: permisos de un rol sobre un módulo.
--   leer -> consultar   escribir -> dar de alta   editar -> modificar y dar de baja
CREATE TABLE IF NOT EXISTS public.roles_modulos
(
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol    bigint NOT NULL REFERENCES public.roles (id)   ON DELETE CASCADE,
    id_modulo bigint NOT NULL REFERENCES public.modulos (id) ON DELETE CASCADE,
    leer      boolean,
    escribir  boolean,
    editar    boolean,
    UNIQUE (id_rol, id_modulo)
);

-- roles_paneles: pantallas que ve cada rol.
CREATE TABLE IF NOT EXISTS public.roles_paneles
(
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol   bigint NOT NULL REFERENCES public.roles (id)   ON DELETE CASCADE,
    id_panel bigint NOT NULL REFERENCES public.paneles (id) ON DELETE CASCADE,
    UNIQUE (id_rol, id_panel)
);

-- sesiones: un registro por login. El logout, la baja del usuario o un
-- cambio de contraseña la desactivan.
CREATE TABLE IF NOT EXISTS public.sesiones
(
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       bigint       NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
    token            varchar(255) NOT NULL,
    activo           boolean      NOT NULL,
    fecha_login      timestamptz  NOT NULL,
    fecha_expiracion timestamptz,
    fecha_logout     timestamptz
);
CREATE INDEX IF NOT EXISTS idx_sesiones_token ON public.sesiones (token);

-- recuperaciones_contrasena: pedidos de "¿Olvidaste tu contraseña?".
-- Se guarda el hash SHA-256 del token que viaja en el correo, nunca el token.
CREATE TABLE IF NOT EXISTS public.recuperaciones_contrasena
(
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       bigint      NOT NULL REFERENCES public.usuarios (id) ON DELETE CASCADE,
    token_hash       varchar(64) NOT NULL UNIQUE,
    fecha_alta       timestamptz NOT NULL,
    fecha_expiracion timestamptz NOT NULL,
    fecha_uso        timestamptz
);

COMMIT;
