-- =====================================================================
-- MÓDULO 2 · GESTIÓN DE PROYECTOS
-- Obras, archivo importado, tareas e historial de estados.  4 tablas.
-- =====================================================================
-- Requiere: 1-gestionDeAccesos.sql (tarea e historial apuntan a usuarios).
-- Idempotente (IF NOT EXISTS): se puede correr más de una vez.
-- Los "enums" se guardan como texto y se validan con CHECK.
-- =====================================================================

BEGIN;

-- proyecto: una obra (importada desde el archivo de presupuesto).
CREATE TABLE IF NOT EXISTS public.proyecto
(
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            varchar(150)  NOT NULL UNIQUE,
    descripcion       varchar(1000),
    cliente           varchar(200),
    atencion          varchar(200),
    ref_cliente       varchar(200),
    tipo_cliente      varchar(20)
        CHECK (tipo_cliente IN ('EPE', 'VIALIDAD', 'PRIVADO', 'INDUSTRIA')),
    tipo_obra         varchar(20)
        CHECK (tipo_obra IN ('ZANJEO', 'ILUMINACION', 'REDES_ENERGIA', 'INDUSTRIAL', 'OTRA')),
    estado            varchar(20)   NOT NULL
        CHECK (estado IN ('PLANIFICADO', 'EN_CURSO', 'FINALIZADO')),
    fecha_inicio      date,
    fecha_fin         date,
    archivo_nombre    varchar(255),
    fecha_importacion timestamp,
    linea_base_fecha  timestamp       -- cuándo se congeló la planificación original
);

-- archivo_proyecto: el archivo original importado (1 a 1 con proyecto).
CREATE TABLE IF NOT EXISTS public.archivo_proyecto
(
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id    bigint NOT NULL UNIQUE REFERENCES public.proyecto (id),
    contenido      bytea  NOT NULL,
    tipo_contenido varchar(100)
);

-- tarea: tareas de la obra, en árbol (padre_id). avance = % físico (0-100).
CREATE TABLE IF NOT EXISTS public.tarea
(
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id       bigint       NOT NULL REFERENCES public.proyecto (id),
    padre_id          bigint       REFERENCES public.tarea (id),
    responsable_id    bigint       REFERENCES public.usuarios (id),
    numero            varchar(20),
    orden             integer,
    nombre            varchar(150) NOT NULL,
    descripcion       varchar(1000),
    estado            varchar(20)  NOT NULL
        CHECK (estado IN ('PENDIENTE', 'EN_PROGRESO', 'COMPLETADA')),
    prioridad         varchar(10)
        CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    avance            integer,
    fecha_inicio      date,            -- planificada
    fecha_fin         date,            -- planificada
    fecha_inicio_real date,
    fecha_fin_real    date
);

-- historial_estado_tarea: cada cambio de estado de una tarea y quién lo hizo.
CREATE TABLE IF NOT EXISTS public.historial_estado_tarea
(
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarea_id        bigint      NOT NULL REFERENCES public.tarea (id),
    usuario_id      bigint      REFERENCES public.usuarios (id),
    estado_anterior varchar(20)
        CHECK (estado_anterior IN ('PENDIENTE', 'EN_PROGRESO', 'COMPLETADA')),
    estado_nuevo    varchar(20) NOT NULL
        CHECK (estado_nuevo IN ('PENDIENTE', 'EN_PROGRESO', 'COMPLETADA')),
    fecha_hora      timestamp   NOT NULL
);

COMMIT;
